"""Extract and verify the two source DOCX files using only Python's standard library."""
from pathlib import Path
import json
import re
import zipfile
import xml.etree.ElementTree as ET

WEB = Path(__file__).resolve().parents[1]
SOURCE = WEB.parent / 'Câu hỏi Giáo Trình'
NS = {'w': 'http://schemas.openxmlformats.org/wordprocessingml/2006/main'}


def extract(course, total, first_lesson, last_lesson):
    filename = f'AZOTA_GIAO_TRINH_{course.upper()}_{total}_CAU_CO_DAP_AN.docx'
    with zipfile.ZipFile(SOURCE / filename) as archive:
        root = ET.fromstring(archive.read('word/document.xml'))
    paragraphs = [(''.join(t.text or '' for t in p.findall('.//w:t', NS)), p)
                  for p in root.findall('.//w:p', NS)]
    key = {}
    for text, _ in paragraphs:
        if match := re.fullmatch(r'(\d+)\.([ABCD])', text.strip()):
            number = int(match[1])
            if number in key:
                raise ValueError(f'Duplicate answer: {course}/{number}')
            key[number] = match[2]
    lessons, questions, highlighted = [], [], {}
    lesson = None
    if first_lesson == 2:
        lessons.append({'number': 1, 'title': 'Đối tượng, phương pháp nghiên cứu môn học GDQP&AN', 'count': 0})
    for text, paragraph in paragraphs:
        if match := re.match(r'CHỦ ĐỀ (\d+):\s*(.*?)\s*\((\d+) câu\)$', text):
            lesson = int(match[1])
            lessons.append({'number': lesson, 'title': match[2], 'count': int(match[3])})
        elif match := re.match(r'Câu (\d+)\.\s*(.*)', text):
            number = int(match[1])
            questions.append({'id': f'{course}-{number:03}', 'course': course,
                              'lesson': lesson, 'sourceNumber': number,
                              'text': match[2], 'options': [], 'answer': key.get(number)})
            highlighted[number] = []
        elif questions and (match := re.match(r'([ABCD])\.\s*(.*)', text)):
            questions[-1]['options'].append({'letter': match[1], 'text': match[2]})
            if paragraph.findall('.//w:highlight', NS):
                highlighted[questions[-1]['sourceNumber']].append(match[1])
    assert len(questions) == len(key) == total, f'{course}: incorrect totals'
    assert [q['sourceNumber'] for q in questions] == list(range(1, total + 1))
    assert [l['number'] for l in lessons if l['count']] == list(range(first_lesson, last_lesson + 1))
    for question in questions:
        assert question['text'] and question['lesson'] is not None
        assert [o['letter'] for o in question['options']] == list('ABCD')
        assert all(o['text'] for o in question['options'])
        assert highlighted[question['sourceNumber']] == [question['answer']], question['id']
    for item in lessons:
        assert sum(q['lesson'] == item['number'] for q in questions) == item['count']
    print(f'{course.upper()}: verified {total} questions; highlights match answer table.')
    return {'id': course, 'name': course.upper(), 'source': filename, 'lessons': lessons, 'questions': questions}


if __name__ == '__main__':
    data = {'version': 1, 'courses': [extract('qp1', 200, 2, 11), extract('qp2', 140, 1, 7)]}
    output = WEB / 'data' / 'questions.js'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('/* Generated by tools/extract_questions.py. */\nwindow.QP_DATA = '
                      + json.dumps(data, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
